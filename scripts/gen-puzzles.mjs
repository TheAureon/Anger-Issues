// Bakes the puzzle library into chess-shooter/src/puzzle-data.js.
// Every puzzle is generated at random (fixed seed) and kept only if a search proves it works.
//   node scripts/gen-puzzles.mjs
import { writeFileSync } from 'node:fs';
import * as R from '../chess-shooter/src/rules.js';
import * as G from '../chess-shooter/src/puzzlegen.js';

const rng = R.mulberry(20261112);
const out = [];
const sq = (s) => R.sqName(s);
function add(pack, n, made, extra) {
  const t0 = Date.now();
  let i = 0;
  let misses = 0;
  while (i < n) {
    const r = made();
    if (!r) {
      if (++misses > 20) throw new Error(`${pack}: generator keeps failing`);
      continue;
    }
    const id = `${pack}-${i + 1}`;
    out.push({ id, pack, placement: G.toPlacement(r.st), mode: r.st.mode, sure: !!(r.st.rules && r.st.rules.spreadMul === 0), hint: { from: sq(r.solution.from), to: sq(r.solution.to) }, ...(r.st.cover && r.st.cover.length ? { cover: r.st.cover.map(sq) } : {}), ...extra(r) });
    i++;
  }
  console.log(`${pack}: ${n} puzzles in ${((Date.now() - t0) / 1000).toFixed(1)}s`);
}
add('basic', 8, () => G.genDrill(rng), () => ({ ai: 'easy', goal: { type: 'king', n: 1 } }));
add('two', 8, () => G.genTwoMover(rng), () => ({ ai: 'brutal', goal: { type: 'king', n: 2 } }));
add('trick', 6, () => G.genTrickShot(rng), (r) => ({ ai: 'easy', goal: { type: 'kill', n: 1, target: sq(r.target) }, window: Math.round(r.window * 100), aim: { x: +r.aim.x.toFixed(3), y: +r.aim.y.toFixed(3), z: +r.aim.z.toFixed(3) } }));
add('survive', 5, () => G.genSurvival(rng), () => ({ ai: 'brutal', goal: { type: 'survive', n: 2 } }));
add('odds', 5, () => G.genOdds(rng), (r) => ({ ai: 'easy', goal: { type: 'odds', n: 1 }, best: Math.round(r.best * 100) }));
add('rescue', 4, () => G.genRescue(rng), () => ({ ai: 'brutal', goal: { type: 'promote', n: 2 } }));
add('weekly', 6, () => G.genTwoMover(rng, true), () => ({ ai: 'brutal', goal: { type: 'king', n: 2 } }));

const src = `// Generated by scripts/gen-puzzles.mjs. Do not edit by hand: change the generator and re-run it.
export const PUZZLE_DATA = ${JSON.stringify(out, null, 0).replace(/},{/g, '},\n  {').replace('[{', '[\n  {').replace(/}]$/, '},\n]')};
`;
writeFileSync(new URL('../chess-shooter/src/puzzle-data.js', import.meta.url), src);
console.log(`wrote ${out.length} puzzles`);
