// Turns a Vite build (dist/dev.html + assets) into one self-contained HTML file.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

// Usage: node scripts/make-playable.mjs <project folder> <output file>, both relative to the repo root.
//   node scripts/make-playable.mjs . anger-issues.html
//   node scripts/make-playable.mjs chess-shooter index.html
const repo = join(dirname(fileURLToPath(import.meta.url)), '..');
const root = join(repo, process.argv[2] || '.');
const out = process.argv[3] || 'index.html';
const dist = join(root, 'dist');
let html = readFileSync(join(dist, 'dev.html'), 'utf8');

// Inline stylesheets.
html = html.replace(/<link rel="stylesheet"[^>]*href="\.\/([^"]+)"[^>]*>/g, (_, file) => {
  const css = readFileSync(join(dist, file), 'utf8');
  return `<style>\n${css}\n</style>`;
});

// Inline the module script, moved to the end of <body> (inline modules still run deferred-style there).
let scripts = '';
html = html.replace(/<script type="module"[^>]*src="\.\/([^"]+)"[^>]*><\/script>\s*/g, (_, file) => {
  const js = readFileSync(join(dist, file), 'utf8').replace(/<\/script/gi, '<\\/script');
  scripts += `<script type="module">\n${js}\n</script>\n`;
  return '';
});
if (!scripts) throw new Error('No module script found in dist/dev.html');
// Function replacers: the bundle contains `$&`-style sequences that string replacements would expand.
html = html.replace('</body>', () => `${scripts}</body>`);
html = html.replace('<head>', () => '<head>\n    <!-- Generated by `npm run build` from dev.html + src/. Do not edit by hand. -->');

if (/(src|href)="\.\/assets\//.test(html)) throw new Error('Unresolved asset reference left in output');
writeFileSync(join(repo, out), html);
writeFileSync(join(dist, 'index.html'), html);
console.log(`${out} written (${(html.length / 1024 / 1024).toFixed(2)} MB, self-contained)`);
